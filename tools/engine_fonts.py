"""Write engine/fonts/kamishibai-fonts.css: the fonts of the slides as base64 @font-face rules.

  python3 tools/engine_fonts.py                  (or: make engine-fonts)

The Madrid theme uses its own font CSS kept in the repository (engine/fonts/cm-sans.css,
engine/fonts/ipa-pgothic.css); this script does not touch them.

A draft deck opened from file:// cannot fetch font files (the browser treats them as cross-origin),
so the runtime engine (engine/kamishibai.js) loads the fonts from a stylesheet with the font data
inside. The fonts are embedded whole (no subsetting): the file is large, which is fine for drafts.
Needs the font files in fonts/ (make fonts). The output is generated and git-ignored.
"""
import base64, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "fonts"
OUT = ROOT / "engine" / "fonts" / "kamishibai-fonts.css"

# (CSS family, weight, font file in fonts/). The families named by --font in engine/themes/Boadilla.css.
FONTS = [
    ("LMSans", 400, "lmsans10-regular.otf"),
    ("LMSans", 700, "lmsans10-bold.otf"),
    ("JPGothic", 400, "HaranoAjiGothic-Regular.otf"),
    ("JPGothic", 700, "HaranoAjiGothic-Bold.otf"),
    ("LMItalic", 400, "lmroman10-italic.otf"),
]

HEADER = """/* Fonts of the Kamishibai engine, generated by tools/engine_fonts.py (do not edit).
   Latin Modern Sans / Latin Modern Roman Italic: GUST Font License (fonts/LICENSE-LatinModern.txt).
   Harano Aji Gothic: SIL Open Font License 1.1 (fonts/LICENSE-HaranoAji.txt).
   The fonts are embedded unmodified. The copyright notices and license texts follow. */
"""
LICENSE_FILES = ["LICENSE-HaranoAji.txt", "LICENSE-LatinModern.txt"]


def license_notice(names):
    """A CSS comment with the copyright notice of each font file (name ID 0) and the license texts,
    so that the fonts carry their notices wherever the stylesheet goes (SIL OFL 1.1, condition 2)."""
    from fontTools.ttLib import TTFont
    lines = []
    for name in dict.fromkeys(names):
        font = TTFont(FONT_DIR / name, lazy=True)
        lines.append(f"{name}: {font['name'].getDebugName(0) or '(no copyright notice in the font)'}")
    texts = [(FONT_DIR / f).read_text(encoding="utf-8") for f in LICENSE_FILES]
    body = "\n".join(lines) + "\n\n" + "\n\n".join(texts)
    return "/* Font copyright notices and licenses\n" + body.replace("*/", "* /") + "\n*/\n"


def main(argv):
    if argv:
        sys.exit(__doc__)
    rules = [HEADER]
    for fam, wt, name in FONTS:
        path = FONT_DIR / name
        if not path.exists():
            sys.exit(f"font not found: {path}\nrun  make fonts  (or python3 tools/fetch_fonts.py)")
        data = base64.b64encode(path.read_bytes()).decode("ascii")
        rules.append(f'@font-face{{font-family:"{fam}";font-style:normal;font-weight:{wt};font-display:block;'
                     f'src:url(data:font/otf;base64,{data}) format("opentype")}}\n')
    rules.insert(1, license_notice([n for _, _, n in FONTS]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(rules), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main(sys.argv[1:])
